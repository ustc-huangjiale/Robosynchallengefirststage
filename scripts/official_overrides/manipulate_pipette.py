@register_env("ManipulatePipette", max_episode_steps=600)
class ManipulatePipetteEnv(EmbodiedEnv):
    def __init__(self, cfg: EmbodiedEnvCfg = None, **kwargs):
        super().__init__(cfg, **kwargs)

        action_config = kwargs.get("action_config", None)
        if action_config is not None:
            self.action_config = action_config

    def _init_sim_state(self, **kwargs):
        super()._init_sim_state(**kwargs)
        # BaseEnv obtains its initial observation before our __init__ returns.
        self._pipette_min_reach_count = torch.zeros(
            self.num_envs, dtype=torch.int32, device=self.device
        )
        self._pipette_was_at_min = torch.zeros(
            self.num_envs, dtype=torch.bool, device=self.device
        )
        self._pipette_press_event = torch.zeros_like(self._pipette_was_at_min)
        self._pipette_min_tolerance = 1e-4
        self._refresh_pipette_state()
        self._pipette_was_at_min.copy_(self._pipette_metrics["pipette_at_min"][:, 0])

    def create_demo_action_list(self, *args, **kwargs):
        """
        Create a demonstration action list for the current task.

        Returns:
            list: A list of demo actions generated by the task.
        """
        logger.log_info("Create demo action list for ManipulatePipetteTask.")
        if getattr(self, "action_config", None) is not None:
            self._init_action_bank(ManipulatePipetteActionBank, self.action_config)
            action_list = self.create_expert_demo_action_list(*args, **kwargs)
        else:
            raise ValueError("ManipulatePipette requires action_config for collection")

        if action_list is None:
            return action_list

        logger.log_info(
            f"Demo action list created with {len(action_list)} steps.", color="green"
        )
        return action_list

    def create_expert_demo_action_list(self, **kwargs):
        """
        Create an expert demonstration action list using the action bank.

        This function generates a trajectory based on expert knowledge, mapping joint and end-effector
        states to the required action format for the environment and robot type.

        Args:
            **kwargs: Additional keyword arguments.

        Returns:
            list: A list of actions, each containing joint positions ("qpos").
        """

        if hasattr(self, "action_bank") is False or self.action_bank is None:
            logger.log_error(
                "Action bank is not initialized. Cannot create expert demo action list."
            )

        if self.num_envs != 1:
            raise ValueError("Pipette expert collection supports num_envs=1 only")

        ret = self.action_bank.create_action_list(
            self, self.graph_compose, self.packages
        )

        if ret is None:
            logger.log_warning("Failed to generate expert demo action list.")
            return None

        # TODO: to be removed, need a unified interface in robot class
        left_arm_joints = self.robot.get_joint_ids(name="left_arm", remove_mimic=True)
        right_arm_joints = self.robot.get_joint_ids(name="right_arm", remove_mimic=True)
        left_eef_joints = self.robot.get_joint_ids(name="left_eef", remove_mimic=True)
        right_eef_joints = self.robot.get_joint_ids(name="right_eef", remove_mimic=True)


        total_traj_num = ret[list(ret.keys())[0]].shape[-1]
        num_active_joints = len(self.active_joint_ids)
        actions = torch.zeros(
            (total_traj_num, self.num_envs, num_active_joints), dtype=torch.float32
        )

        # 建立一个从全局 joint_id 到 active_joint_id 在 action 数组中正确存放位置的映射
        global_to_active_idx = {
            joint_id: active_idx for active_idx, joint_id in enumerate(self.active_joint_ids)
        }

        for key, joints in [
            ("left_arm", left_arm_joints),
            ("left_eef", left_eef_joints),
            ("right_arm", right_arm_joints),
            ("right_eef", right_eef_joints),
        ]:
            if key in ret:
                # TODO: only 1 env supported now
                local_action_data = torch.as_tensor(ret[key].T, dtype=torch.float32)

                # 使用映射精准定位它在 action tensor 中的正确位置存放
                for i, joint_id in enumerate(joints):
                    if joint_id in global_to_active_idx:
                        active_idx = global_to_active_idx[joint_id]
                        actions[:, 0, active_idx] = local_action_data[:, i]
        return actions

    def _update_sim_state(self, **kwargs):
        super()._update_sim_state(**kwargs)
        # Exactly once per physical control step, BEFORE get_obs/recording.
        self._refresh_pipette_state(count_press=True)

    def _extend_obs(self, obs, **kwargs):
        obs = super()._extend_obs(obs, **kwargs)
        for name, value in self._pipette_metrics.items():
            obs[name] = value.clone()
        return obs

    def compute_task_state(self, **kwargs):
        # Complete the expert trajectory; reset saves only a successful ending.
        done = torch.zeros_like(self._success_flag)
        return done, done.clone(), {
            name: value.clone() for name, value in self._pipette_metrics.items()
        }

    def is_task_success(self, **kwargs) -> torch.Tensor:
        return self._success_flag.clone()

    def close(self):
        # LeRobotRecorder.finalize otherwise writes every unfinished buffer,
        # bypassing reset's success filter (including interrupted failures).
        # Only reset is allowed to commit Pipette episodes.
        if getattr(self, "rollout_buffer", None) is not None:
            self.current_rollout_step = 0
        return super().close()

    def _evaluate_task_state(self):
        failed = (self._pipette_metrics["beaker1_fallen"][:, 0]
                  | self._pipette_metrics["pipette_fallen"][:, 0])
        return self.is_task_success(), failed.clone()

    def _initialize_episode(self, env_ids=None, **kwargs):
        # The parent saves the previous rollout before clearing its buffers.
        super()._initialize_episode(env_ids=env_ids, **kwargs)
        ids = (torch.arange(self.num_envs, device=self.device) if env_ids is None
               else torch.as_tensor(env_ids, dtype=torch.long, device=self.device))
        self._pipette_min_reach_count[ids] = 0
        self._pipette_press_event[ids] = False
        self._refresh_pipette_state()
        # Starting already depressed is not a new press by the policy.
        self._pipette_was_at_min[ids] = self._pipette_metrics["pipette_at_min"][ids, 0]

    def _refresh_pipette_state(self, count_press=False):
        pipette = self.sim.get_articulation("pipette")
        beaker = self.sim.get_rigid_object("beaker1")
        pipette_pose = pipette.get_local_pose(to_matrix=True).clone()
        beaker_pose = beaker.get_local_pose(to_matrix=True).clone()
        for name, pose in (("pipette", pipette_pose), ("beaker1", beaker_pose)):
            self._validate_pose(name, pose)

        qpos = pipette.get_qpos()[:, 0].clone()
        limits = self._get_pipette_slide_limits(pipette)
        if not torch.isfinite(qpos).all():
            raise ValueError("Non-finite pipette slide position; refusing invalid GT")
        threshold = 0.66 * limits[:, 0] + self._pipette_min_tolerance
        at_min = qpos <= threshold
        if count_press:
            self._pipette_press_event = at_min & ~self._pipette_was_at_min
            self._pipette_min_reach_count += self._pipette_press_event.to(torch.int32)
            self._pipette_was_at_min = at_min.clone()

        beaker_tilt = torch.acos(beaker_pose[:, 2, 2].clamp(-1, 1))
        pipette_tilt = torch.acos(pipette_pose[:, 2, 0].clamp(-1, 1))
        beaker_fallen = beaker_tilt >= torch.pi / 9
        pipette_fallen = pipette_tilt >= torch.pi / 9
        # Preserve the released official predicate: one press, currently upright.
        self._success_flag = ((self._pipette_min_reach_count >= 1)
                              & ~beaker_fallen & ~pipette_fallen)
        scalars = {
            "pipette_slide_qpos": qpos,
            "pipette_press_threshold": threshold,
            "pipette_at_min": at_min,
            "pipette_press_event": self._pipette_press_event,
            "pipette_min_reach_count": self._pipette_min_reach_count,
            "beaker1_tilt_rad": beaker_tilt,
            "pipette_tilt_rad": pipette_tilt,
            "beaker1_fallen": beaker_fallen,
            "pipette_fallen": pipette_fallen,
            "task_success": self._success_flag,
        }
        # LeRobot scalar features need shape [1], not a zero-dimensional shape.
        self._pipette_metrics = {key: value[:, None].clone() for key, value in scalars.items()}
        self._pipette_metrics.update(
            pipette_pose=pipette_pose, beaker1_pose=beaker_pose,
            pipette_slide_limits=limits.clone(),
        )

    def _validate_pose(self, name, pose):
        if pose.shape != (self.num_envs, 4, 4) or not torch.isfinite(pose).all():
            raise ValueError(f"Invalid {name} pose shape or values; refusing invalid GT")
        rotation = pose[:, :3, :3]
        bottom = pose.new_tensor([0, 0, 0, 1]).expand(self.num_envs, -1)
        identity = torch.eye(3, device=pose.device, dtype=pose.dtype).expand(self.num_envs, -1, -1)
        if (not torch.allclose(pose[:, 3, :], bottom, atol=1e-5, rtol=0)
                or not torch.allclose(rotation @ rotation.transpose(-1, -2), identity, atol=1e-3, rtol=0)
                or not torch.all(torch.linalg.det(rotation) > 0)):
            raise ValueError(f"Invalid {name} rigid transform; refusing invalid GT")

    def _get_pipette_slide_limits(self, pipette):
        limits = getattr(pipette, "qpos_limits", None)
        if limits is None and hasattr(pipette, "body_data"):
            limits = pipette.body_data.qpos_limits
        if limits is None:
            limits = [entity.get_joint_limits() for entity in pipette.entities]
        limits = torch.as_tensor(limits, device=self.device, dtype=torch.float32)
        if (limits.ndim != 3 or limits.shape[0] != self.num_envs
                or limits.shape[1] < 1 or limits.shape[2] != 2):
            raise ValueError("Invalid pipette joint limit shape")
        slide = limits[:, 0, :]
        if not torch.isfinite(slide).all() or not torch.all(slide[:, 0] < slide[:, 1]):
            raise ValueError("Invalid pipette slide limits")
        return slide

    def _get_pipette_slide_min(self, pipette) -> torch.Tensor:
        return self._get_pipette_slide_limits(pipette)[:, 0]




@register_env("ManipulatePipetteTest", max_episode_steps=600)
class ManipulatePipetteTestEnv(ManipulatePipetteEnv):
    def compute_task_state(self, **kwargs):
        success, fail = self._evaluate_task_state()
        return success, fail, None


@register_env("ManipulatePipetteAgent", max_episode_steps=600)
class ManipulatePipetteAgentEnv(BaseAgentEnv, ManipulatePipetteEnv):
    def __init__(self, cfg: EmbodiedEnvCfg = None, **kwargs):
        super().__init__(cfg, **kwargs)
        super()._init_agents(**kwargs)

    def reset(self, seed: Optional[int] = None, options: Optional[Dict] = None):
        obs, info = super().reset(seed=seed, options=options)
        super().get_states()
        return obs, info
